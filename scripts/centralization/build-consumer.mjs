import { readFileSync, writeFileSync } from 'node:fs';
// Package the very same tested planner for Apps Script; no parallel mapping or dependency.
let core=readFileSync(new URL('./enrollment-plan.mjs',import.meta.url),'utf8');
core=core.replace(/^import .+;\r?\n/gm,'');
const cli=core.indexOf('\nif (process.argv[1]');
if(cli<0)throw Error('Planner CLI boundary changed');
core=core.slice(0,cli).replace(/^export /gm,'');
if(/\b(?:import|process|readFileSync|writeFileSync|pathToFileURL)\b/.test(core))throw Error('Node-only code in planner bundle');
const adapter=readFileSync(new URL('./central-consumer-adapter.gs',import.meta.url),'utf8');
writeFileSync(new URL('../../docs/apps-script/PUENTE_CENTRAL_CONSULTA.gs',import.meta.url),
  '// Generated by node scripts/centralization/build-consumer.mjs. Do not edit the bundled core.\n'
  +'var VORTEX_PLAN_CORE_=(function(){\n'+core+'\nreturn {planEnrollments:planEnrollments};\n})();\n'+adapter);
console.log('Bundled existing planner and central consultation adapter. No external changes.');
